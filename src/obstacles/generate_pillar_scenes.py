"""Emit the pillar scene YAMLs and pillar SDFs.

    python -m src.obstacles.generate_pillar_scenes          # write
    python -m src.obstacles.generate_pillar_scenes --check  # exit 1 if any file differs

One YAML per (record robot, pillar rung): `<hardened stem without _hardened>_pillars_rXXX.yaml`
next to the hardened file = a GENERATED header + the hardened text verbatim + four appended
directives.  One SDF per rung at `models/assets/pillar_rXXX.sdf`.  Rule: `pillars.py`.
"""

import os
import sys

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "../../")))

from src.obstacles.pillars import PILLAR_HEIGHT, PILLAR_RADII, PillarCentres, PillarSceneName

RECORD_ROBOTS = ("panda", "iiwa", "screw7_p050", "soft12")
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))


def SdfPath(r):
    return "models/assets/pillar_r%03d.sdf" % round(r * 1000)


def RenderSdf(r):
    name = "pillar_r%03d" % round(r * 1000)
    mass = 10.0
    ixx = mass * (3 * r * r + PILLAR_HEIGHT ** 2) / 12.0
    izz = mass * r * r / 2.0
    geom = ("<cylinder><radius>%g</radius><length>%g</length></cylinder>" % (r, PILLAR_HEIGHT))
    return f"""<?xml version="1.0"?>
<!-- GENERATED by src/obstacles/generate_pillar_scenes.py. Do not edit. -->
<sdf version="1.7">
  <model name="{name}">
    <link name="pillar_link">
      <inertial>
        <mass>{mass:g}</mass>
        <inertia>
          <ixx>{ixx:.6g}</ixx><iyy>{ixx:.6g}</iyy><izz>{izz:.6g}</izz>
          <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz>
        </inertia>
      </inertial>
      <visual name="visual">
        <geometry>{geom}</geometry>
        <material><diffuse>0.55 0.55 0.6 1.0</diffuse></material>
      </visual>
      <collision name="collision">
        <geometry>{geom}</geometry>
      </collision>
    </link>
  </model>
</sdf>
"""


def HardenedPath(robot):
    from src.target_screening import SCENES
    return SCENES[(robot, "mug")].hardened


def PillarYamlPath(robot, r):
    h = HardenedPath(robot)
    assert h.endswith("_hardened.yaml"), h
    return h[:-len("_hardened.yaml")] + "_%s.yaml" % PillarSceneName(r)


def RenderYaml(robot, r):
    with open(os.path.join(ROOT, HardenedPath(robot))) as f:
        base = f.read()
    sdf = "package://combining_kinematics/" + SdfPath(r)
    head = ("# GENERATED by src/obstacles/generate_pillar_scenes.py. Do not edit: a test asserts\n"
            "# this file is byte-exactly what the generator emits.\n"
            "# %s = %s verbatim plus four floor-to-ceiling pillars of radius %g m\n"
            "# (src/obstacles/pillars.py states the rule).\n"
            % (os.path.basename(PillarYamlPath(robot, r)),
               os.path.basename(HardenedPath(robot)), r))
    tail = "\n  # Pillars in front of the shelf units (family PILLAR)\n"
    for k, (x, y) in enumerate(PillarCentres(r), start=1):
        tail += (f"  - add_model:\n      name: pillar{k}\n      file: {sdf}\n\n"
                 f"  - add_weld:\n      parent: world\n      child: pillar{k}::pillar_link\n"
                 f"      X_PC:\n        translation: [{x:.9f}, {y:.9f}, {PILLAR_HEIGHT / 2:.1f}]\n")
        if k < 4:
            tail += "\n"
    return head + base + tail


def ExpectedFiles():
    """{repo-relative path: text} of every generated file."""
    out = {}
    for r in PILLAR_RADII:
        out[SdfPath(r)] = RenderSdf(r)
        for robot in RECORD_ROBOTS:
            out[PillarYamlPath(robot, r)] = RenderYaml(robot, r)
    return out


def main(argv=None):
    check = "--check" in (sys.argv[1:] if argv is None else argv)
    bad = 0
    for rel, text in ExpectedFiles().items():
        path = os.path.join(ROOT, rel)
        if check:
            have = open(path).read() if os.path.exists(path) else None
            if have != text:
                print("DIFFERS:", rel)
                bad += 1
        else:
            with open(path, "w") as f:
                f.write(text)
            print("wrote", rel)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
