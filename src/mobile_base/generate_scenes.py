"""Emit the mobile-base scenes: every robot on the same KMR-style planar base, in the same room.

THE LAYOUT (Thomas, 2026-11-25: "KMR-style new layout") is `../codebase`'s Basic Mobile
Manipulator scene, `models/kmriiwa/kmriiwa_with_iiwa.dmd.yaml`, re-expressed with this repo's
own models -- nothing is imported from `../codebase`; the numbers are copied, with provenance:

  * four shelf units at (+-0.85, 0) and (0, +-0.85), centre height 1.396706, facing the centre;
  * a central table (`table_extra_wide_better_collision.sdf`'s collision boxes) at z 0.996706,
    which the shelves stand on;
  * the KUKA KMP200 platform: a 1.1216 x 0.6304 x 0.6672 m collision box, the arm mounted at
    `kmriiwa_mount_frame` (0.363, -0.184, 0.7) with yaw -1.5708, from `kmriiwa.urdf`.

The shelf UNIT is this repo's `models/assets/shelves.sdf`, not the PR2 copy `../codebase` uses
(3 mm wider wall spacing, no bottom board): the compartment definition is then literally the
hardened scene's (`src/shelf_regions.py`), and only the welds differ.

THE BASE is two prismatic joints and a revolute joint, world -> x -> y -> yaw, exactly the KMR
URDF's structure. Two deliberate differences from that file:
  * its `<limit>` is written as ATTRIBUTES -- the KMR file nests child elements, which Drake
    ignores, so its base loaded unbounded (../codebase GLOBAL_IK_BASELINE GI6); here the plant
    carries the base box itself, x, y in [-2, 2] m (../codebase's target/sampling box) and yaw
    in [-2 pi, 2 pi] (every start draws yaw in [-pi, pi], so no start sits on the seam);
  * wheels, lasers and meshes are dropped: the collision model is the one box, which is all the
    KMR row ever collided with (its mesh and sensor collisions are commented out there).

THE ARM BLOCK of each scene is lifted TEXTUALLY from that robot's hardened scene -- the arm, its
gripper and any arm-internal filter group -- with the single `parent: world` weld of the arm's
base rewritten to the mount frame. So the arm, its default positions and its gripper are
byte-identical to the record's, and the generator raises if that weld is not found exactly once.

ONE FILTER, the same on every robot: the arm's base link against the platform it is bolted to.
On the fixed-base scenes this came for free -- both were anchored, and Drake never generates
anchored-anchored candidates -- and on the soft PCS arm it extends to the sub-link spheres its
hardened scene filters against the tables it was mounted through (read from that scene, not
retyped). Nothing else of the arm is filtered against the platform.
"""

import math
import os
import re

from src.utils import RepoDir

MOBILE_MODEL = "mobile_base"
PLATFORM_BODY = "kmriiwa_base_link"
MOUNT_FRAME = "kmriiwa_mount_frame"
BASE_JOINTS = ("platform_x", "platform_y", "platform_yaw")

#: ../codebase kmriiwa.urdf: footprint -> base_link +0.025 z; box centre/size; top +0.675;
#: mount (0.363, -0.184, 0) yaw -1.5708 on the top link.
_FOOTPRINT_Z = 0.025
_BOX_CENTRE = (0.0202, 0.0002, 0.3336)
_BOX_SIZE = (1.1216, 0.6304, 0.6672)
_TOP_Z = 0.675
_MOUNT_XYZ = (0.363, -0.184, 0.0)
_MOUNT_YAW = -1.5708
_XY_LIMIT = 2.0
_YAW_LIMIT = 2.0 * math.pi
#: ../codebase kmriiwa_with_iiwa.dmd.yaml default base positions; the "home" start rule.
HOME_BASE = (1.5, 0.0, 0.0)

_TABLE_Z = 0.996706
_SHELF_Z = 1.396706
#: (name, x, y, yaw_deg) -- ../codebase shelf_1..4 welds.
MOBILE_SHELVES = (("shelves", 0.85, 0.0, -180.0),
                  ("shelves2", 0.0, 0.85, -90.0),
                  ("shelves3", -0.85, 0.0, 0.0),
                  ("shelves4", 0.0, -0.85, 90.0))

_PLATFORM_URI = "package://combining_kinematics/models/mobile_base/kmr_platform.urdf"
_TABLE_URI = "package://combining_kinematics/models/mobile_base/central_table.sdf"
_SHELF_URI = "package://combining_kinematics/models/assets/shelves.sdf"

#: robot key -> (hardened scene, mobile scene, the arm's base link as `instance::body`).
ROBOTS = {
    "panda": ("models/panda/panda_finray_collision_hardened.yaml",
              "models/panda/panda_finray_collision_mobile.yaml", "panda::panda_link0"),
    "iiwa": ("models/iiwa14/iiwa14_collision_hardened.yaml",
             "models/iiwa14/iiwa14_collision_mobile.yaml", "iiwa::base"),
    "screw7_p050": ("models/screw7_p050/screw7_p050_collision_hardened.yaml",
                    "models/screw7_p050/screw7_p050_collision_mobile.yaml",
                    "screw7_p050::base_link"),
    "soft12": ("models/soft12/soft12_collision_hardened.yaml",
               "models/soft12/soft12_collision_mobile.yaml", "soft12::base"),
}


