"""Render `cusp7` as an SDFormat model, from `params.py` and nothing else.

The link, joint and inertia blocks are the screw arm's (`src.screw_arm.generate_sdf`):
every joint here is revolute, so its blocks carry no screw element. SDFormat rather than
URDF because Drake parses `<drake:collision_filter_group>` from SDFormat only, so the
filters live in the model rather than in the scene directives. Collision is the declared
sphere union; the cylinder is visual only.
"""

import os
import sys

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "../../")))

from src.cusp_arm.params import (A2, A5, COLLISION_CHAIN_GAP, D4, LINKS, SCALE, SPECS,
                                 CuspArmSpec)
from src.screw_arm.generate_sdf import EFFORT, VELOCITY, _link_block


def _joint_block(joint) -> str:
    """One revolute joint. The screw arm's block prints poses to 1e-6, which is exact for
    its axis-aligned origins but would put a 1e-6 rad error into every pi/2 twist here; the
    pose is printed at full precision (`repr`) instead."""
    pose = " ".join(repr(float(v)) for v in (*joint.origin_xyz, *joint.origin_rpy))
    ax, ay, az = joint.axis
    return f"""    <joint name="{joint.name}" type="{joint.kind}">
      <pose relative_to="{joint.parent}">{pose}</pose>
      <parent>{joint.parent}</parent>
      <child>{joint.child}</child>
      <axis>
        <xyz>{ax:.6f} {ay:.6f} {az:.6f}</xyz>
        <limit>
          <lower>{joint.lower!r}</lower><upper>{joint.upper!r}</upper>
          <effort>{EFFORT}</effort><velocity>{VELOCITY}</velocity>
        </limit>
      </axis>
    </joint>"""


def _filter_blocks() -> str:
    """One group per link ignoring every link nearer than `COLLISION_CHAIN_GAP` along the
    chain -- the same rule `COLLISION_PAIRS` encodes, so the dataset screen and the solver
    see one robot. Groups carry the `cfg_` prefix (SDFormat needs unique child names)."""
    out = []
    for i, link in enumerate(LINKS):
        near = [f"cfg_{LINKS[j].name}" for j in range(len(LINKS))
                if j != i and abs(j - i) < COLLISION_CHAIN_GAP]
        ignores = "".join(
            f"\n        <drake:ignored_collision_filter_group>{n}"
            f"</drake:ignored_collision_filter_group>" for n in near)
        out.append(
            f'    <drake:collision_filter_group name="cfg_{link.name}">\n'
            f"        <drake:member>{link.name}</drake:member>{ignores}\n"
            f"    </drake:collision_filter_group>")
    return "\n".join(out)


def RenderSdf(spec: CuspArmSpec) -> str:
    parents = {j.child: j.name for j in spec.joints}
    body = "\n".join(_link_block(link, parents.get(link.name)) for link in spec.links)
    joints = "\n".join(_joint_block(j) for j in spec.joints)
    return f"""<?xml version="1.0"?>
<!-- GENERATED by src/cusp_arm/generate_sdf.py from src/cusp_arm/params.py.
     Do not edit: a test asserts this file is byte-exactly what the generator emits.

     {spec.name}: the simplified Transpressor 6R of Feess & Weiss (arXiv 2602.14794), a cuspidal
     6R, at a2 = {A2:.3f}, d4 = {D4:.3f}, a5 = {A5:.3f} m (the paper's 3 / 2 / 0.5 x {SCALE}), plus a
     tool pitch at the wrist end. -->
<sdf version="1.11">
  <model name="{spec.name}">
{body}
{joints}
{_filter_blocks()}
  </model>
</sdf>
"""


def OutputPath(spec: CuspArmSpec, root: str) -> str:
    return os.path.join(root, "models", spec.name, f"{spec.name}.sdf")


def main():
    root = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../"))
    for spec in SPECS.values():
        path = OutputPath(spec, root)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(RenderSdf(spec))
        print(f"wrote {os.path.relpath(path, root)}")


if __name__ == "__main__":
    main()
