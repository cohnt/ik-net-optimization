#!/usr/bin/env python3
"""List the SNOPT shards of the record that hold a cell past the overrun watcher's threshold.

The overrun watcher (cluster/run_items.sh, 2026-10-21) kills a solve past 1.5x its clock. The
record was measured before it, so every shard with a cell past that threshold is re-run whole and
verbatim under the watcher (stage OVR, Thomas 2026-10-21: whole affected shards, not single cells).
This reads the collected shard summaries and writes `cluster/overrun_rerun_items.txt`: one
`<committed manifest>|<item id>` line per affected shard, which `cluster/gen_manifest.py`'s stage
OVR reads.

    python scripts/find_overrun_shards.py [--factor 1.5] [--write]
"""
import argparse
import glob
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
#: The stages whose SNOPT shards are re-run, by the committed manifest they came from. REMEASURE
#: carries the record's rows and the GVS arm (outside the record); PAPER the record's seconds;
#: ANALYTIC both clip ladders (tags ANALYTIC, ANALYTICT); ANALYTIC_CPP the C++ backend (ANALYTICC).
MANIFESTS = ("REMEASURE", "PAPER", "ANALYTIC", "ANALYTIC_CPP")
OUT = os.path.join(REPO, "cluster", "overrun_rerun_items.txt")


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--factor", type=float, default=1.5)
    p.add_argument("--write", action="store_true", help=f"write {os.path.relpath(OUT, REPO)}")
    args = p.parse_args()
    os.chdir(REPO)

    owner = {}
    for m in MANIFESTS:
        with open(f"cluster/manifest_stage{m}.txt") as fh:
            for line in fh:
                if line.strip() and not line.startswith("#"):
                    owner[line.split("|", 1)[0]] = m
    shards = {}
    for root in ("results", "results/_cluster_staging/*/results"):
        for f in sorted(glob.glob(f"{root}/*/benchmark/sc_*_snopt_*_shard*/summary.json")):
            shards.setdefault(os.path.basename(os.path.dirname(f)), []).append(f)

    lines, missing = [], 0
    for tag in sorted(shards):
        if tag not in owner:
            continue
        hits = set()
        for f in shards[tag]:
            with open(f) as fh:
                s = json.load(fh)
            limit = args.factor * float(s["metadata"].get("wall_time") or 180.0)
            hits.add(any((r.get("wall_time") or 0.0) > limit
                         for recs in s["records"].values() for r in recs))
        if len(hits) > 1:
            raise SystemExit(f"{tag}: collected copies disagree")
        if hits.pop():
            lines.append(f"{owner[tag]}|{tag}")
    snopt = [i for i, m in owner.items() if "_snopt_" in i]
    missing = sorted(i for i in snopt if i not in shards)
    for m in MANIFESTS:
        print(f"{m:<14} {sum(1 for l in lines if l.startswith(m + '|')):>4} shard(s)")
    if missing:
        print(f"WARNING: {len(missing)} SNOPT item(s) of these manifests have no collected shard, "
              f"e.g. {missing[:3]}")
    if args.write:
        with open(OUT, "w") as fh:
            fh.write(f"# SNOPT shards with a cell past {args.factor:g}x the clock, re-run by stage OVR\n"
                     "# generated by scripts/find_overrun_shards.py --write; <manifest>|<item id>\n")
            fh.write("\n".join(lines) + "\n")
        print(f"wrote {os.path.relpath(OUT, REPO)} ({len(lines)} items)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
