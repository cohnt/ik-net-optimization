#!/usr/bin/env python3
"""Emit the mobile-base manifests (docs/notes-mobile-base.md; ops cluster/MOBILE_BASE_RUNBOOK.md).

Every item is a record item with the scene swapped: the flags are stage REMEASURE's (IPOPT, both
arms in one run) and the AL-SVGD pin's (R29 `pin4` learned / R30 `pin4kq` joint space), with
`--scene hardened` replaced by `--scene mobile --base-start <rule>` and the kernel by its mobile
counterpart (`cz` -> `bcz`, `q` -> `bq`; base-blind kernels are refused on a mobile program).
Nothing else differs: 180 s, lifted budgets, `--compile --set flow_cuda_graph=True`, native
starts, seed 1, shelf-contained targets (fingertips for pose).

    python cluster/csail/gen_mobile_manifest.py smoke -o cluster/csail/manifest_mb_smoke.txt
    python cluster/csail/gen_mobile_manifest.py pilot -o cluster/csail/manifest_mb_pilot.txt

Tags (= item ids) start with `mb_<STAGE>_`; `scripts/report_mobile.py --prefix mb_PILOT_` reads them.
"""
import argparse
import os

RULES = ("uniform", "facing", "home")
TASKS = ("mug", "pose")
ROBOTS = {   # name -> (driver, robot-selection args, checkpoint): the record's charts
    "panda": ("scripts/panda/panda_benchmark.py", "",
              "models/panda/panda__n6__step620000.pkl"),
    "iiwa": ("scripts/iiwa/iiwa_benchmark.py", "",
             "models/iiwa14/iiwa14__n4__step620000.pkl"),
    "screw7_p050": ("scripts/screw_arm/screw_arm_benchmark.py", "--robot screw7_p050",
                    "models/screw7_p050/screw7_p050__n6__step620000.pkl"),
    "soft12": ("scripts/soft_arm/soft_arm_benchmark.py", "--rung soft12",
               "models/soft12/soft12__n6__step620000.pkl"),
}
CHART = {"panda": "n6", "iiwa": "n4", "screw7_p050": "n6", "soft12": "n6"}
SVGD_PIN = ("--set svgd_compile=True --set svgd_cuda_graph=True --set svgd_collision_backend=clearances "
            "--set svgd_outer_iters=1000000 --set svgd_kernel={kernel} --set svgd_rho=100000 "
            "--set svgd_paired_init=native --set svgd_gn_lm=10 --set svgd_lr=0.3 "
            "--set svgd_stop_patience=3")
COMBOS = {   # combo token -> (arms, solver, solver flags)
    "ipopt": ("learned,numerical", "ipopt", "--set max_iter=1000000"),
    "svgdL": ("learned", "svgd", SVGD_PIN.format(kernel="bcz")),
    "svgdJ": ("numerical", "svgd", SVGD_PIN.format(kernel="bq")),
}
STAGES = {   # stage -> (targets, guesses, wall, robots, tasks, rules)
    "PILOT": (16, 4, 180.0, ("panda", "iiwa", "screw7_p050", "soft12"), TASKS, RULES),
    # plumbing only: the GPU / CUDA-graph mobile path (uncovered locally) on a rigid arm, the
    # screw arm's grasp and the soft PCS arm's composed map; never a measurement.
    "SMOKE": (2, 2, 60.0, ("panda", "screw7_p050", "soft12"), None, ("facing",)),
}
SMOKE_TASK = {"panda": "pose", "screw7_p050": "mug", "soft12": "pose"}


def items(stage):
    targets, guesses, wall, robots, tasks, rules = STAGES[stage]
    for robot in robots:
        driver, robot_args, ckpt = ROBOTS[robot]
        for task in (tasks or (SMOKE_TASK[robot],)):
            for rule in rules:
                for combo, (arms, solver, solver_args) in COMBOS.items():
                    tag = f"mb_{stage}_{robot}_{CHART[robot]}_{task}_{rule}_{combo}"
                    placement = ("--target-placement shelf --placement-point fingertips"
                                 if task == "pose" else "--target-placement shelf")
                    args = " ".join(filter(None, [
                        f"--targets {targets} --guesses {guesses} --wall-time {wall}",
                        f"--arms {arms} --seed 1 --compile --tag {tag}",
                        f"--task {task} --start native --solver {solver} {placement}",
                        "--config latent --set correction_cost_weight=10.0",
                        f"--scene mobile --base-start {rule} --shelf-inset 0.1",
                        robot_args, f"--checkpoint {ckpt}",
                        "--set flow_cuda_graph=True", solver_args]))
                    assert "|" not in args and tag.isascii()
                    yield f"{tag}|-|{driver}|{args}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", choices=[s.lower() for s in STAGES])
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()
    stage = a.stage.upper()
    lines = list(items(stage))
    head = [f"# learned-ik mobile-base {stage}: generated by cluster/csail/gen_mobile_manifest.py "
            "(do not edit by hand).",
            "# format: <id>|<env assignments or ->|<script>|<args>   (the id is the run's tag)"]
    with open(a.output, "w") as f:
        f.write("\n".join(head + lines) + "\n")
    print(f"{len(lines)} items -> {os.path.relpath(a.output)}")


if __name__ == "__main__":
    main()
