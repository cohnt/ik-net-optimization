#!/bin/bash
# Regenerate cluster/engaging/constraints.txt from the workstation venv (laptop side, no network beyond uv's
# local read of the venv). Usage: bash cluster/engaging/make_constraints.sh [venv]   then review `git diff`.
# Constraints only pin what pip installs; they install nothing. Filtered out: editable and URL/local entries
# (ikflow is the vendored fork on PYTHONPATH, jrl is installed from its pinned commit), anything tied to the
# laptop's CUDA build (torch, nvidia-*, triton: torch 2.14.0+cu126 brings its own cu126 runtime) and pip.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
VENV="${1:-$HERE/../../.venv}"
OUT="$HERE/constraints.txt"
{
    cat <<'EOF'
# pip CONSTRAINTS for the Engaging image (lik.def: every `pip install -c`): the workstation venv's
# `uv pip freeze`, so no package moves to a new release behind our back (setuptools 82 dropped
# pkg_resources, which ikflow imports; the venv has 78.1.0). Generated by cluster/engaging/make_constraints.sh;
# regenerate and review the diff, never edit by hand.
# Filtered out: editable and URL/local entries, torch/nvidia-*/cuda-*/triton (the laptop's CUDA build), pip.
# The image's torch, pinned to its CUDA build:
torch==2.14.0+cu126
EOF
    uv pip freeze --python "$VENV/bin/python" 2>/dev/null | grep -vE '^(-e |#)|@ |^torch==|^nvidia-|^cuda-|^triton==|^pip==|file:' | sort -f
} > "$OUT"
echo "wrote $OUT: $(grep -vc '^#' "$OUT") pins"
