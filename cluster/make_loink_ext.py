#!/usr/bin/env python3
"""Write stage LOINKEXT / LOINKEXT_SVGD from the collected LOINKPROBE / LOINKPROBE_SVGD summaries.

The probe-first design (cluster/LOINK_RUNBOOK.md; the cVAE precedent, cluster/make_cvae_probe.py):
stage LOINKPROBE runs every RIGID-arm chart x task x start as one 60-cell item (guess 0 of every
target), native AND paired -- the LOInK inverse is exact, so a paired probe is a real solve -- and
soft12's rows in full. The rule, fixed before any probe was run:

    every rigid chart x row (solver, task, start) whose 60-cell probe solved >= 1 cell
    gets its full 480-cell row.

A full row's items are the would-be full stage's own (gen_manifest.stage_LOINK("LOINKFULL") /
("LOINKFULL_SVGD"), sharded 8 / 24 as stage CVAE), byte for byte, so the probe's 60 cells are
re-solved inside the row and the row pairs with the record like any other. No verdict is read
off a probe: it only decides which rows are run in full.

The selection logic lives in cluster/gen_manifest.py (loink_ext_selection, stage_LOINK), so
`gen_manifest.py --stage LOINKEXT --summary --procs 2` prices exactly what this writes. A probe
counts as COLLECTED when its merged summary (unsharded `sc_LOINK_*_60_180_*`, under results/ or
results/_cluster_staging/*/results/, report_statusquo.load's roots) holds all 60 learned records.
Before any probe is collected the manifests are written EMPTY, and this says so; a probe not yet
collected keeps its row out (it is listed), so re-run this after each collect -- item ids are
stable, and run_items.sh's state is keyed by the manifest's basename, so a resubmitted LOINKEXT
skips the items already done.

    python cluster/make_loink_ext.py                      # (re)write both manifests
    python cluster/make_loink_ext.py --check              # exit 1 if the committed ones are stale
    python cluster/make_loink_ext.py --summary --procs 2  # also print each stage's item-hours
"""

import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_manifest as gm  # noqa: E402

STAGES = (("LOINKEXT", False), ("LOINKEXT_SVGD", True))


def manifest_text(which, svgd, outcomes):
    qualifying, collected, missing = gm.loink_ext_selection(svgd, outcomes)
    items = gm.stage_LOINK(which, outcomes=outcomes)
    lines = gm.render(items)
    probe = "LOINKPROBE_SVGD" if svgd else "LOINKPROBE"
    n_rows = len(collected) + len(missing)
    header = [f"# learned-ik stage {which} manifest",
              f"# generated by cluster/make_loink_ext.py from the collected {probe} summaries "
              "(edit the rule there / in gen_manifest.py, not here)",
              "# rule: every rigid chart x row whose 60-cell probe solved >= 1 cell gets its full "
              "480-cell row (LOINKFULL's items)",
              f"# probes collected: {len(collected)} of {n_rows}; rows qualifying: {len(qualifying)}",
              "# format: <id>|<env assignments or ->|<script>|<args>",
              f"# {len(lines)} items, ordered by schedule group (the stage's `order`), LPT within each"]
    return "\n".join(header + lines) + "\n", items, qualifying, collected, missing


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    p.add_argument("--check", action="store_true",
                   help="exit 1 if a committed manifest differs from what the collected probes give")
    p.add_argument("--summary", action="store_true", help="print each stage's item-hours")
    p.add_argument("--procs", type=int, default=2, help="workers per node, for --summary")
    p.add_argument("--nodes", type=int, default=4, help="nodes, for --summary")
    args = p.parse_args()

    outcomes = gm.loink_probe_outcomes()
    if not outcomes:
        print("NO LOInK probe summary collected yet (sc_LOINK_*_60_180_* with 60 learned records): "
              "the EXT manifests are EMPTY.")
    stale = False
    for which, svgd in STAGES:
        text, items, qualifying, collected, missing = manifest_text(which, svgd, outcomes)
        path = HERE / f"manifest_stage{which}.txt"
        n_ok = sum(1 for s in collected.values() if s >= 1)
        print(f"{which}: {len(collected)} probes collected, {n_ok} with >= 1 success -> "
              f"{len(qualifying)} full rows, {len(items)} items")
        for tag in sorted(collected):
            print(f"  {tag}: {collected[tag]}/{gm.LOINK_PROBE_TARGETS}"
                  f"{'  -> full row' if collected[tag] >= 1 else ''}")
        if missing:
            print(f"  {len(missing)} probe(s) NOT collected -- their rows are not in {which}:")
            for tag in missing[:12]:
                print(f"    {tag}")
            if len(missing) > 12:
                print(f"    ... and {len(missing) - 12} more")
        if args.summary and items:
            gm.summarise(items, args.procs, args.nodes)
        if args.check:
            if not path.exists() or path.read_text() != text:
                print(f"  STALE: {path.name}")
                stale = True
        else:
            path.write_text(text)
            print(f"  wrote {os.path.relpath(path, HERE.parent)}")
    if args.check and stale:
        raise SystemExit("stale LOINKEXT manifests: re-run cluster/make_loink_ext.py")


if __name__ == "__main__":
    main()
