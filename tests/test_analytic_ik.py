"""The closed-form maps themselves: the iiwa's Faria S-R-S map and the Panda's He-Liu map.

No flow, no program -- only `src/iiwa_analytic_ik.py` and `src/panda_analytic_ik.py`. Run by
hand, one file at a time:

    python tests/test_analytic_ik.py

What it pins:
  * the iiwa port agrees with ../codebase's maintained map (committed golden file,
    regenerated by scripts/make_iiwa_analytic_golden.py) on FK, psi, q and the clip args;
  * `Solve(FK(q), psi(q), gc(q)) == q` -- the round trip -- and prints its coverage curve at
    both clip ladders, because coverage is a property of the clip as much as of the chart;
  * `Solve` returns q and the pre-clip arguments of ONE pass, equal to the old two-call API;
  * AutoDiffXd derivatives of q and u against central differences;
  * a pose out of reach clips with zero derivative on the clipped joint while the
    reported argument keeps a nonzero one (so a reachability row can still see it);
  * the Panda's q6 lands in [seam, seam + 2pi) and on its in-limit representative.
Tiers (tests/_tiers.py): the default `fast` runs in ~8 s on one CPU core; no `slow` group.
"""
import os
import sys
import time

import numpy as np

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import _tiers                                                             # noqa: E402

from pydrake.all import AutoDiffXd, InitializeAutoDiff, ExtractGradient, RigidTransform  # noqa: E402
from src.iiwa_analytic_ik import (Analytic_IK_7DoF, iiwa_limits_lower,       # noqa: E402
                                  iiwa_limits_upper)
from src.panda_analytic_ik import (Analytic_IK_Panda, Q6_WRAP_SEAM,          # noqa: E402
                                   panda_limits_lower, panda_limits_upper)

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAILURES = []
CHECKS = [0]

IIWA = Analytic_IK_7DoF()
PANDA = Analytic_IK_Panda()

#: The two clip ladders fielded (Thomas, 2026-10-12: measure both).
LADDERS = {"codebase": 1e-4, "tight": 1e-8}


def check(name, condition, detail=""):
    CHECKS[0] += 1
    if condition:
        print(f"  ok    {name}")
    else:
        print(f"  FAIL  {name}\n          {detail}")
        FAILURES.append(name)


def wrapped(a):
    return np.abs(np.angle(np.exp(1j * np.asarray(a, dtype=float))))


## ---- the two maps behind one signature: (q, clip, x=None) -> (q_out, u) ---- ##

def iiwa_solve(q, clip, R=None, p=None, psi=None):
    X = IIWA.FK(q)
    return IIWA.Solve(X[:3, :3] if R is None else R, X[:3, 3] if p is None else p,
                      IIWA.GC(q), IIWA.psi(q) if psi is None else psi, clip)


def panda_solve(q, clip, R=None, p=None, psi=None, branches=3):
    X = PANDA.FK(q)
    return PANDA.Solve(X[:3, :3] if R is None else R, X[:3, 3] if p is None else p,
                       q[6] if psi is None else psi, PANDA.gc(q, branches), clip)


def test_iiwa_codebase_parity():
    print("iiwa: parity with ../codebase (golden)")
    g = np.load(os.path.join(REPO, "tests/data/iiwa_analytic_codebase_golden.npz"))
    fk = psi = qq = uu = 0.0
    for q, X, gc, (p0, pe), q_ik, u in zip(g["q"], g["X"], g["gc"], g["psi"], g["q_ik"], g["u"]):
        fk = max(fk, np.abs(IIWA.FK(q) - X).max())
        psi = max(psi, abs(IIWA.psi(q) - p0))
        np.testing.assert_array_equal(IIWA.GC(q), gc)
        qa, ua = IIWA.Solve(X[:3, :3], X[:3, 3], gc, pe)
        qq = max(qq, np.abs(qa - q_ik).max())
        uu = max(uu, np.abs(ua - u).max())
    check("FK agrees", fk < 1e-12, fk)
    check("psi agrees", psi < 1e-10, psi)
    check("q agrees (off the recovered psi too)", qq < 1e-10, qq)
    check("all four clip arguments agree", uu < 1e-10, uu)


def coverage(name, solve, lo, hi, n=2000):
    rng = np.random.default_rng(0)
    qs = [rng.uniform(lo, hi) for _ in range(n)]
    out = {}
    for ladder, clip in LADDERS.items():
        errs = np.array([wrapped(solve(q, clip)[0] - q).max() for q in qs])
        out[ladder] = errs
        curve = "  ".join(f"<{t:g}: {np.mean(errs < t):.4f}" for t in (1e-8, 1e-6, 1e-3, 1e-2))
        print(f"    {name:7s} clip {clip:g} ({ladder}): {curve}")
    return out


def test_round_trip():
    print("round trip Solve(FK(q), psi(q), gc(q)) == q, uniform over the limits")
    iiwa = coverage("iiwa", iiwa_solve, iiwa_limits_lower, iiwa_limits_upper)
    p8 = coverage("panda8", panda_solve, panda_limits_lower, panda_limits_upper)
    p4 = coverage("panda4", lambda q, c: panda_solve(q, c, branches=2),
                  panda_limits_lower, panda_limits_upper)
    ## Floors, not targets: at the tight clip both full charts cover every draw; at the
    ## codebase clip the loss is the band within ~sqrt(2e-4) rad of a chart seam.
    check("iiwa covers >= 99.9% at the tight clip", np.mean(iiwa["tight"] < 1e-6) >= 0.999)
    check("panda8 covers >= 99.9% at the tight clip", np.mean(p8["tight"] < 1e-6) >= 0.999)
    check("iiwa covers >= 96% at the codebase clip", np.mean(iiwa["codebase"] < 1e-6) >= 0.96)
    check("panda8 covers >= 93% at the codebase clip", np.mean(p8["codebase"] < 1e-6) >= 0.93)
    ## The 4-branch chart misses the elbow branch A = -1 (~10% of configurations).
    check("panda4 covers 84-90% at the tight clip", 0.84 <= np.mean(p4["tight"] < 1e-6) <= 0.90,
          np.mean(p4["tight"] < 1e-6))


def test_one_pass_matches_old_api():
    print("Solve returns the old IK(...) and IK(..., return_unclipped_vals=True) together")
    rng = np.random.default_rng(3)
    worst = 0.0
    for _ in range(50):
        q = rng.uniform(panda_limits_lower, panda_limits_upper)
        X = RigidTransform(PANDA.FK(q))
        gc = PANDA.gc(q, 3)
        qa, ua = PANDA.Solve(X.rotation().matrix(), X.translation(), q[6], gc, 1e-6)
        worst = max(worst, np.abs(qa - PANDA.IK(X, q[6], gc)).max(),
                    np.abs(ua - PANDA.IK(X, q[6], gc, return_unclipped_vals=True)).max())
        q = rng.uniform(iiwa_limits_lower, iiwa_limits_upper)
        X = RigidTransform(IIWA.FK(q))
        qa, ua = IIWA.Solve(X.rotation().matrix(), X.translation(), IIWA.GC(q), 0.3)
        worst = max(worst, np.abs(qa - IIWA.IK(X, IIWA.GC(q), 0.3)).max(),
                    np.abs(ua - IIWA.IK(X, IIWA.GC(q), 0.3, return_unclipped_vals=True)).max())
    check("bit-identical", worst == 0.0, worst)


def _rpy_pose(x):
    from pydrake.all import RollPitchYaw_, RigidTransform_
    t = AutoDiffXd if isinstance(x[0], AutoDiffXd) else float
    X = RigidTransform_[t](RollPitchYaw_[t](x[3:6]), x[:3])
    return X.rotation().matrix(), X.translation()


def jacobian_check(name, f, x0):
    '''f: 7-vector (xyz, rpy, psi) -> (q, u). AutoDiffXd against central differences.'''
    ad = InitializeAutoDiff(x0)[:, 0]
    q_ad, u_ad = f(ad)
    J = np.vstack([ExtractGradient(np.asarray(q_ad)), ExtractGradient(np.asarray(u_ad))])
    h = 1e-6
    Jfd = np.zeros_like(J)
    for i in range(len(x0)):
        e = np.zeros(len(x0))
        e[i] = h
        qp, up = f(x0 + e)
        qm, um = f(x0 - e)
        Jfd[:, i] = np.concatenate([np.angle(np.exp(1j * (qp - qm))), up - um]) / (2 * h)
    err = np.abs(J - Jfd).max() / max(1.0, np.abs(J).max())
    values = np.concatenate([[v.value() for v in q_ad], [v.value() for v in u_ad]])
    vf = np.concatenate(f(x0))
    check(f"{name}: AutoDiffXd values equal float", np.abs(values - vf).max() < 1e-12)
    check(f"{name}: AutoDiffXd Jacobian matches central differences (rel {err:.1e})",
          err < 1e-6, err)


def test_gradients():
    print("AutoDiffXd derivatives of (q, u) against central differences")
    ## Draws within ~0.1 rad of an arccos branch point (|u| > 0.99) are skipped: there the
    ## derivative is steep and a central difference's h^2 truncation dominates (measured:
    ## at |u| = 0.9997 the mismatch falls exactly as h^2 from 66 at h = 1e-4 to 5e-5 at
    ## 1e-7 -- the AutoDiffXd value is right, the reference is not).
    rng = np.random.default_rng(5)
    def away_from_band(solve, lo, hi):
        while True:
            q = rng.uniform(0.8 * lo, 0.8 * hi)
            if np.abs(solve(q, 1e-4)[1]).max() < 0.99:
                return q
    for k in range(3):
        q = away_from_band(iiwa_solve, iiwa_limits_lower, iiwa_limits_upper)
        X = RigidTransform(IIWA.FK(q))
        x0 = np.concatenate([X.translation(), X.rotation().ToRollPitchYaw().vector(), [IIWA.psi(q)]])
        gc = IIWA.GC(q)
        jacobian_check(f"iiwa draw {k}",
                       lambda x: IIWA.Solve(*_rpy_pose(x), gc, x[6], 1e-4), x0)
        q = away_from_band(panda_solve, panda_limits_lower, panda_limits_upper)
        X = RigidTransform(PANDA.FK(q))
        x0 = np.concatenate([X.translation(), X.rotation().ToRollPitchYaw().vector(), [q[6]]])
        gc = PANDA.gc(q, 3)
        jacobian_check(f"panda draw {k}",
                       lambda x: PANDA.Solve(*_rpy_pose(x), x[6], gc, 1e-4), x0)


def test_out_of_reach_clips():
    print("a pose out of reach: clipped joint has zero derivative, its argument does not")
    q = np.array([0.3, 0.8, -0.2, -1.2, 0.4, 1.0, 0.1])
    X = IIWA.FK(q)
    p_far = X[:3, 3] * 3.0  # well past the 1.18 m reach
    x = InitializeAutoDiff(p_far)[:, 0]
    qa, ua = IIWA.Solve(X[:3, :3], x, IIWA.GC(q), 0.2, 1e-4)
    u0 = ua[0]
    check("the elbow argument reports past 1", u0.value() > 1.0, u0.value())
    check("the elbow argument keeps a nonzero derivative",
          np.linalg.norm(u0.derivatives()) > 0)
    check("the clipped elbow joint has a zero derivative",
          np.linalg.norm(qa[3].derivatives()) == 0.0, qa[3].derivatives())
    check("the returned configuration is finite",
          np.all(np.isfinite([v.value() for v in qa])))


def test_panda_q6_window():
    print("Panda q6 is returned in [seam, seam + 2pi) and on its in-limit representative")
    rng = np.random.default_rng(7)
    q6s, misses = [], 0
    for _ in range(2000):
        q = rng.uniform(panda_limits_lower, panda_limits_upper)
        qa, _ = panda_solve(q, 1e-8)
        q6s.append(qa[5])
        ## Only a draw the chart reproduces can be asked to land on q6 itself.
        misses += abs(qa[5] - q[5]) > 1e-6 and np.abs(qa - q).max() < 1e-6
    q6s = np.array(q6s)
    check("every q6 in the window", np.all((q6s >= Q6_WRAP_SEAM) & (q6s < Q6_WRAP_SEAM + 2 * np.pi)),
          (q6s.min(), q6s.max()))
    check("q6 equals the drawn value on every reproduced draw", misses == 0, misses)


def test_timing():
    print("cost per Solve (printed; one core)")
    rng = np.random.default_rng(9)
    for name, solve, lo, hi in (("iiwa", iiwa_solve, iiwa_limits_lower, iiwa_limits_upper),
                                ("panda", panda_solve, panda_limits_lower, panda_limits_upper)):
        qs = [rng.uniform(lo, hi) for _ in range(200)]
        t = time.perf_counter()
        for q in qs:
            solve(q, 1e-4)
        dt = (time.perf_counter() - t) / len(qs) * 1e6
        X0 = (IIWA if name == "iiwa" else PANDA).FK(qs[0])
        x = InitializeAutoDiff(np.concatenate([X0[:3, 3], [0.1]]))[:, 0]
        t = time.perf_counter()
        for _ in range(50):
            solve(qs[0], 1e-4, p=x[:3], psi=x[3])
        da = (time.perf_counter() - t) / 50 * 1e6
        print(f"    {name}: {dt:.0f} us float, {da:.0f} us AutoDiffXd (4 derivatives, incl. FK)")


GROUPS = {"fast": [test_iiwa_codebase_parity, test_round_trip, test_one_pass_matches_old_api,
                   test_gradients, test_out_of_reach_clips, test_panda_q6_window, test_timing]}


